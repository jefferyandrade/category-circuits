"""Replayable context streams over a frozen training axis: two sampling laws.

Law 1 -- independent logical draws WITH replacement (``BinaryIIDSamplingDesign``,
``StratifiedIIDSamplingDesign``; ``sampling_with_replacement = True``).
The physical training axis is finite, but calibration and proposal
adjudication target repeated independent draws from its declared empirical
distribution.  A draw therefore has two identities:

* ``draw_id`` is the unique statistical observation identity;
* ``source_context_id`` is the physical image/context selected by that draw.

Different draws may select the same source context.  Runtime providers may
deduplicate those physical evaluations and expand the resulting value back to
the draw axis, but the statistical receipt retains every draw multiplicity.

Law 2 -- sealed simple random sampling WITHOUT replacement
(``StratifiedSealedWithoutReplacementSamplingDesign``;
``sampling_with_replacement = False``).  Each (role, stream, stratum) owns a
uniform permutation of that stratum's finite population, sealed by the same
SHA-256 rejection rule as law 1 before any outcome is observed.  Draw ``i`` is
the ``i``-th element of that permutation, generated by a sparse forward
Fisher--Yates step, so the first ``k`` draws are a uniform simple random sample
of size ``k`` without replacement, prefixes nest (``draw_range(0, k)`` is a
prefix of ``draw_range(0, k + m)``), no source context repeats, and revealing
``k`` draws costs ``k`` hashes and ``O(k)`` memory.  A stratum is exhausted
exactly when ``k == N_h``: the prefix is then the stratum's exact census and
further draws raise.  The finite-population correction ``(1 - n_h / N_h)`` is
therefore exact for the interval built on these draws.

The two laws are distinct scientific identities: their designs hash
differently on identical populations, their draw ids carry different
prefixes (``iid:`` / ``swor:``), and their receipts state the law explicitly.
"""

