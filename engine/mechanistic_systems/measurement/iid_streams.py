BINARY_IID_STRATA = ("on_target", "off_target")
BINARY_IID_DESIGN_SCHEMA = "binary_empirical_iid_sampling_design_v1"
STRATIFIED_IID_DESIGN_SCHEMA = "stratified_empirical_iid_sampling_design_v1"
BINARY_IID_STREAM_ALGORITHM = "sha256_rejection_empirical_iid_v1"
STRATIFIED_SEALED_WOR_DESIGN_SCHEMA = (
    "stratified_sealed_without_replacement_sampling_design_v1"
)
